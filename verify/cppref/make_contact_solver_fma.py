#!/usr/bin/env python3
# Generates contact_solver_fma.c from the pinned C source: the scalar
# (BOX2D_DISABLE_SIMD) bodies of b2MulAddW/b2MulSubW become explicit fmaf so
# the reference computes the deterministic single-rounding fused form at
# exactly the sites the relaxed AS artifact fuses. Everything else is
# byte-identical to the pin.
import sys

src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()

muladd = "\treturn (b2FloatW){ a.x + b.x * c.x, a.y + b.y * c.y, a.z + b.z * c.z, a.w + b.w * c.w };"
muladd_fma = ("\treturn (b2FloatW){ fmaf( b.x, c.x, a.x ), fmaf( b.y, c.y, a.y ), "
              "fmaf( b.z, c.z, a.z ), fmaf( b.w, c.w, a.w ) };")
mulsub = "\treturn (b2FloatW){ a.x - b.x * c.x, a.y - b.y * c.y, a.z - b.z * c.z, a.w - b.w * c.w };"
mulsub_fma = ("\treturn (b2FloatW){ fmaf( -b.x, c.x, a.x ), fmaf( -b.y, c.y, a.y ), "
              "fmaf( -b.z, c.z, a.z ), fmaf( -b.w, c.w, a.w ) };")

assert s.count(muladd) == 1, "b2MulAddW scalar body drifted from the pin"
assert s.count(mulsub) == 1, "b2MulSubW scalar body drifted from the pin"
s = s.replace(muladd, muladd_fma, 1).replace(mulsub, mulsub_fma, 1)
s = "// GENERATED by make_contact_solver_fma.py -- do not edit.\n#include <math.h>\n" + s
open(dst, "w").write(s)
print("wrote", dst)
