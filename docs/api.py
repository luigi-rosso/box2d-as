#!/usr/bin/env python3
# Generates docs/api.md: every public Box2D function, by area, against what lib/box2d.as exports.
#   docs/api.py            write docs/api.md
#   docs/api.py --summary  print the area table the README carries
# Public means declared B2_API, B2_INLINE, B2_FORCE_INLINE or B2_ID_INLINE in the upstream headers below.
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
box2d = os.environ.get('BOX2D', os.path.expanduser('~/Projects/box2d'))
include = os.path.join(box2d, 'include', 'box2d')
headers = ['box2d.h', 'collision.h', 'math_functions.h', 'types.h', 'base.h', 'id.h']

AREAS = [
	'world', 'bodies', 'shapes', 'chains', 'contacts', 'joints, common', 'distance joint', 'motor joint', 'mover joint',
	'pogo joint', 'prismatic joint', 'revolute joint', 'weld joint', 'wheel joint',
	'geometry, collision and dynamic tree', 'math', 'ids', 'defaults and defs', 'base', 'debug draw',
	'recording, replay and snapshots',
]

DEBUG_DRAW = {'b2World_Draw', 'b2DefaultDebugDraw', 'b2GetGraphColor'}

# Why each function that lib/box2d.as does not export is left out
REASONS = [
	(lambda n: area_of(n) == 'debug draw', 'debug draw'),
	(lambda n: area_of(n) == 'recording, replay and snapshots', 'recording, replay and snapshots'),
	(lambda n: n == 'b2World_DumpMemoryStats', 'prints C allocator stats'),
]

# Exported, but with nothing to do here: the runtime owns memory and threads
NO_EFFECT = {
	'b2SetAllocator': 'the runtime allocates',
	'b2GetByteCount': 'returns 0, the runtime allocates',
	'b2IsAVX2Available': 'returns false',
	'b2Yield': 'returns at once',
	'b2World_SetWorkerCount': 'sizes the per worker storage, which caps the parts of a parallel call',
}


def area_of(name, header=None):
	header = header or declared.get(name)
	if name in DEBUG_DRAW:
		return 'debug draw'
	if re.match(r'b2Replay_|b2(Create|Destroy)Replay$|b2\w*(Recording|Snapshot)|b2World_GetStateHash$', name):
		return 'recording, replay and snapshots'
	if header == 'id.h':
		return 'ids'
	if re.match(r'b2Default\w*$', name):
		return 'defaults and defs'
	m = re.match(r'b2(Distance|Motor|Mover|Pogo|Prismatic|Revolute|Weld|Wheel)Joint_', name)
	if m:
		return m.group(1).lower() + ' joint'
	if re.match(r'b2Joint_|b2(Create\w*|Destroy)Joint$', name):
		return 'joints, common'
	if re.match(r'b2(Create|Destroy)Chain$|b2Chain_', name):
		return 'chains'
	if name.startswith('b2Contact_'):
		return 'contacts'
	if re.match(r'b2Create\w*Shape$|b2DestroyShape$|b2Shape_', name):
		return 'shapes'
	if re.match(r'b2(Create|Destroy)Body$|b2Body_', name):
		return 'bodies'
	if re.match(r'b2(Create|Destroy)World$|b2World_', name):
		return 'world'
	if header == 'math_functions.h':
		return 'math'
	if header == 'collision.h':
		return 'geometry, collision and dynamic tree'
	if header == 'base.h':
		return 'base'
	return 'world'


def strip(text):
	text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
	text = re.sub(r'//[^\n]*', '', text)
	return re.sub(r'^\s*#.*$', '', text, flags=re.M)


declared = {}
for h in headers:
	body = strip(open(os.path.join(include, h)).read())
	for m in re.finditer(r'\bB2_(?:API|INLINE|FORCE_INLINE|ID_INLINE)\b[^;{(]*?\b([A-Za-z_]\w*)\s*\(', body):
		declared.setdefault(m.group(1), h)

exported = {}
text = open(os.path.join(root, 'lib', 'box2d.as')).read()
for m in re.finditer(r'export\s*\{([^}]*)\}\s*from\s*"\./(\w+)"', text):
	for part in m.group(1).split(','):
		part = part.strip()
		if part:
			exported[part.split(' as ')[-1].strip()] = m.group(2)


def reason_of(name):
	for test, reason in REASONS:
		if test(name):
			return reason
	return 'other'


areas = {a: [] for a in AREAS}
for name in sorted(declared, key=str.lower):
	areas[area_of(name)].append(name)


def summary_rows():
	rows = []
	for area in AREAS:
		names = areas[area]
		if not names:
			continue
		missing = [n for n in names if n not in exported]
		reasons = sorted({reason_of(n) for n in missing})
		note = ''
		if missing and len(missing) == len(names):
			note = 'all: ' + ', '.join(reasons)
		elif missing:
			note = ', '.join('`%s` (%s)' % (n, reason_of(n)) for n in missing)
		rows.append((area, len(names) - len(missing), len(names), note))
	return rows


def summary_table():
	out = ['| area | ported | not ported, and why |', '|---|---|---|']
	total = ported = 0
	for area, p, n, note in summary_rows():
		out.append('| %s | %d / %d | %s |' % (area, p, n, note))
		total += n
		ported += p
	out.append('| **all** | **%d / %d** | |' % (ported, total))
	return out


def write_doc():
	out = [
		'# API availability',
		'',
		'Generated by `docs/api.py` from the public functions of upstream Box2D at 178495b, v3.2.0 (`B2_API` and the',
		'inline functions of `include/box2d/{%s}`) against the names `lib/box2d.as` exports. Regenerate it after' %
		','.join(h[:-2] for h in headers),
		'porting more of the API. Types, enums and constants are exported with the same names and are not listed.',
		'',
	]
	out += summary_table()
	out += ['', '## Not ported', '', '| function | area | why |', '|---|---|---|']
	for area in AREAS:
		for name in areas[area]:
			if name not in exported:
				out.append('| `%s` | %s | %s |' % (name, area, reason_of(name)))
	out += ['', '## Exported with no effect', '', '| function | why |', '|---|---|']
	for name in sorted(NO_EFFECT):
		if name in exported:
			out.append('| `%s` | %s |' % (name, NO_EFFECT[name]))
	out += ['', '## By area', '', 'Each ported function with the `lib/` module that defines it.']
	for area in AREAS:
		names = areas[area]
		if not names:
			continue
		ported = [n for n in names if n in exported]
		out += ['', '### %s (%d / %d)' % (area, len(ported), len(names)), '']
		out += ['| function | module |', '|---|---|']
		for name in names:
			out.append('| `%s` | %s |' % (name, ('`lib/%s.as`' % exported[name]) if name in exported else 'not ported'))
	open(os.path.join(here, 'api.md'), 'w').write('\n'.join(out) + '\n')


if '--summary' in sys.argv:
	print('\n'.join(summary_table()))
else:
	write_doc()
	rows = summary_rows()
	print('wrote docs/api.md: %d of %d functions ported' % (sum(r[1] for r in rows), sum(r[2] for r in rows)))
